import { readFileSync } from "node:fs";

import { expect, test } from "@playwright/test";
import type { Page } from "@playwright/test";

import { TICKER } from "./helpers";

// Phase 7j (Instructions/35_phase7j_earnings_briefs.md): the Earnings tab shows the upcoming
// report date (an estimate marked "~"), the latest post-earnings brief with its AI summary under
// the AI mark, figures that open the citation drawer, "Not available: {reason}" rows for missing
// inputs, a version switcher labelled by what changed, the pre-earnings preview, and a print
// layout whose tables are not clipped on paper. The fixture is a real NVDA response from the dev
// stack (gemini-3.8-flash), recorded to fixtures/earnings-nvda.json.
// Spec refs: FR-EB-002, FR-EB-013, FR-EB-014, FR-EB-015, CIT-EB-001.

const tab = `/company/${TICKER}/earnings`;
const briefsUrl = `**/api/v1/companies/${TICKER}/earnings/briefs`;
const calendarUrl = `**/api/v1/companies/${TICKER}/earnings/calendar`;

type Json = Record<string, unknown> & { items: Record<string, unknown>[] };
const recorded = (): Json =>
  JSON.parse(readFileSync(new URL("../fixtures/earnings-nvda.json", import.meta.url), "utf8")) as Json;

const calendar = {
  ticker: TICKER,
  method: "Reported dates are Item 2.02 8-K filing dates.",
  upcoming: {
    fiscal_year: 2027,
    fiscal_period: "Q3",
    period_label: "Q3 FY2027",
    report_date: "2026-11-18",
    report_time: "unknown",
    source: "estimated",
    status: "scheduled",
    estimated: true,
    source_id: null,
    quote: null,
  },
  events: [],
};

/** The recorded brief as v2, plus a v1 from before the 10-Q was filed. */
function withEarlierVersion(): Json {
  const data = recorded();
  const brief = data.items.find((i) => i.kind === "brief") as Record<string, unknown> & {
    brief: Record<string, unknown> & { missing: unknown[] };
  };
  const v1 = structuredClone(brief);
  Object.assign(v1, { id: 900, version: 1, inputs_label: "after earnings release" });
  v1.brief.what_changed = null;
  v1.brief.missing = [{ section: "what_changed", reason: "10-Q not yet filed." }];
  Object.assign(brief, { version: 2, inputs_label: "after 10-Q filed" });
  data.items = [...data.items.filter((i) => i !== brief), brief, v1];
  return data;
}

async function mock(page: Page, briefs: Json = recorded()) {
  await page.route(briefsUrl, (route) => route.fulfill({ json: briefs }));
  await page.route(calendarUrl, (route) => route.fulfill({ json: calendar }));
}

test("the latest brief: AI summary, cited figures, and an estimated upcoming date", async ({ page }) => {
  await mock(page);
  await page.goto(tab);
  await expect(page.getByRole("region", { name: "Upcoming earnings" })).toContainText("Q3 FY2027 · ~Nov 18, 2026");
  const summary = page.getByRole("region", { name: "Summary" });
  await expect(summary.getByTitle("Generated by AI from cited sources")).toBeVisible();
  await expect(summary.getByRole("button", { name: /Open source/ }).first()).toBeVisible();
  const figures = page.getByRole("region", { name: "Reported figures" });
  await expect(figures.getByRole("columnheader", { name: "Q2 FY2027" })).toBeVisible();
  await expect(page.getByRole("region", { name: "What changed" })).toContainText("risk factors");
  await page.screenshot({ path: "test-results/earnings-brief.png", fullPage: true });

  await figures.getByRole("button", { name: /Open source/ }).first().click();
  await expect(page.getByRole("dialog")).toHaveAccessibleName("Source");
});

test("versions are labelled by what changed; a missing input says so", async ({ page }) => {
  await mock(page, withEarlierVersion());
  await page.goto(tab);
  const version = page.getByRole("combobox", { name: "Version" });
  await expect(version).toHaveValue(String(recorded().items.find((i) => i.kind === "brief")?.id));
  await expect(version.locator("option")).toHaveText(["v2 · after 10-Q filed", "v1 · after earnings release"]);
  await version.selectOption("900");
  await expect(page).toHaveURL(/brief=900/);
  await expect(page.getByRole("region", { name: "What changed" })).toContainText(
    "Not available: 10-Q not yet filed.",
  );
});

test("the preview lists what to watch, each with its sources", async ({ page }) => {
  await mock(page);
  await page.goto(tab);
  await page.getByRole("radio", { name: "Pre-earnings preview" }).click();
  const watch = page.getByRole("region", { name: "What to watch" });
  await expect(watch.getByRole("listitem").first()).toContainText(/slowed to/);
  await expect(page.getByRole("combobox", { name: "Version" }).locator("option")).toHaveCount(2);
  await expect(page.getByRole("region", { name: "Valuation" })).toContainText("×");
  await page.screenshot({ path: "test-results/earnings-preview.png", fullPage: true });
});

test("prints as one document with no clipped tables", async ({ page }) => {
  await mock(page);
  await page.goto(tab);
  await expect(page.getByRole("region", { name: "Reported figures" })).toBeVisible();
  await page.emulateMedia({ media: "print" });
  // On paper no table may be wider than the document (a scroll region would cut it off).
  const clipped = await page.locator(".earnings-print table").evaluateAll((tables) =>
    tables
      .filter((t) => {
        const doc = t.closest(".earnings-print")?.getBoundingClientRect();
        const box = t.getBoundingClientRect();
        return !doc || box.right > doc.right + 1 || t.scrollWidth > t.clientWidth + 1;
      })
      .map((t) => t.querySelector("caption")?.textContent ?? "table"),
  );
  expect(clipped).toEqual([]);
  await expect(page.getByRole("region", { name: "Upcoming earnings" })).toBeHidden();
  const pdf = await page.pdf({ path: "test-results/earnings-brief.pdf", format: "Letter", printBackground: true });
  expect(pdf.byteLength).toBeGreaterThan(10_000);
});
