// Phase 7i (Instructions/34_phase7i_guidance_vs_actual.md): the Filings tab's earnings area shows
// what the company guided to in its own releases, the reported result as a text chip, revenue
// against its guided range by quarter, and the track-record line; a guided figure opens its quote
