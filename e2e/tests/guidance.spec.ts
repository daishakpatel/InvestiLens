test("populated: guided ranges, actuals, the quarter plot and the track record", async ({ page }) => {
  await page.goto(tab);
  const section = page.getByRole("region", { name: "Guidance vs actual" });
  await expect(section.getByTitle("Generated by AI from cited sources")).toBeVisible();
  await expect(section.getByTestId("guidance-track-record")).toContainText(
    /Revenue came in above the guided range in \d+ of \d+ quarters.*\(n=\d+\)/,
  );
  await expect(section.getByText("Above range").first()).toBeVisible();
  await expect(section.getByText("Guided on a non-GAAP basis; GAAP actual not comparable.").first()).toBeVisible();
  await section.screenshot({ path: "test-results/guidance-populated.png" });

  await section.getByRole("button", { name: /Show the quote: Revenue is expected to be/ }).first().click();
  await expect(page.getByRole("dialog")).toHaveAccessibleName("Source");
});

test("a non-GAAP row is shown with its explanation, not hidden", async ({ page }) => {
  await page.route(guidanceUrl, (route) => route.fulfill({ json: guidance }));
  await page.route(recordUrl, (route) => route.fulfill({ json: shortRecord }));
  await page.goto(tab);
  const section = page.getByRole("region", { name: "Guidance vs actual" });
  await expect(section.getByText("Not comparable", { exact: true })).toBeVisible();
  await expect(section.getByText("Guided on a non-GAAP basis; GAAP actual not comparable.")).toBeVisible();
  await expect(section.getByText("Non-GAAP", { exact: true })).toBeVisible();
  await expect(section.getByRole("cell", { name: "+5.7%" })).toBeVisible();
});

test("insufficient history says so with n; no guidance says so", async ({ page }) => {
  await page.route(guidanceUrl, (route) => route.fulfill({ json: guidance }));
  await page.route(recordUrl, (route) => route.fulfill({ json: shortRecord }));
  await page.goto(tab);
  const section = page.getByRole("region", { name: "Guidance vs actual" });
  await expect(section.getByTestId("guidance-track-record")).toHaveText("Insufficient history (n=3)");
  await section.screenshot({ path: "test-results/guidance-insufficient.png" });

  await page.unroute(guidanceUrl);
  await page.route(guidanceUrl, (route) => route.fulfill({ json: { ...guidance, items: [], fiscal_years: [] } }));
  await page.reload();
  await expect(
    page.getByRole("region", { name: "Guidance vs actual" }).getByText(
      "No guidance has been read from this company's earnings releases yet.",
    ),
  ).toBeVisible();
});
