import { expect, test } from "@playwright/test";

import { TICKER } from "./helpers";

// Phase 7f (Instructions/31_phase7f_footnote_extraction.md): the Footnotes tab lists note
// categories, shows XBRL figures (the debt ladder as a chart), AI bullets under an AI marker that
// each open their paragraph, "Not summarised" when the summary abstained, a low-confidence notice,
// and the prior-year comparison scoped to the note. The first test needs the dev stack with the
// dev DB re-parsed and `make footnote-summaries` run; the rest mock the notes response.
// Spec refs: FR-FN-007, FR-FN-010, FR-FN-012.

const tab = `/company/${TICKER}/footnotes`;

test("figures, AI bullets and the note comparison", async ({ page }) => {
  await page.goto(tab);
  const categories = page.getByRole("navigation", { name: "Note categories" });
  await expect(categories.getByRole("button", { name: "Debt" })).toHaveAttribute("aria-current", "true");
  await expect(page.getByRole("heading", { name: "Debt maturities" })).toBeVisible();
  await expect(page.getByText("Not available for", { exact: false })).toBeVisible();

  await categories.getByRole("button", { name: "Leases" }).click();
  await expect(page.getByText("Lease-adjusted debt")).toBeVisible();

  await categories.getByRole("button", { name: "Commitments & contingencies" }).click();
  const summary = page.getByRole("region", { name: /^Summary · Note/ });
  await expect(summary.getByTitle("Generated by AI from cited sources")).toBeVisible();
  await summary.getByRole("button", { name: "Open source 1" }).click();
  await expect(page.getByRole("dialog")).toHaveAccessibleName("Source");
  await page.keyboard.press("Escape");

  await page.getByRole("button", { name: "Compare with prior year" }).click();
  await expect(page.getByTestId("diff-summary")).toContainText("since the 10-K filed");
});

test("an abstained summary says Not summarised, and low confidence is stated", async ({ page }) => {
  await page.route(`**/api/v1/companies/${TICKER}/notes`, (route) =>
    route.fulfill({
      json: {
        company_ticker: TICKER,
        filing: {
          filing_id: "15",
          filing_type: "10-K",
          filing_date: "2026-02-25",
          period_end: "2026-01-25",
          accession_number: "0001045810-26-000021",
        },
        taxonomy: "note_taxonomy_v1",
        low_confidence: true,
        summarised_categories: ["revenue_recognition", "commitments_contingencies", "segments"],
        notes: [
          {
            note_id: "note-16",
            number: 16,
            title: "Segment Information",
            category: "segments",
            also_matches: [],
            paragraph_ids: ["15_15_360"],
            summary: { status: "abstained", bullets: [], model: "mock" },
          },
        ],
      },
    }),
  );
  await page.goto(tab);
  await expect(page.getByText(/could not all be told apart/)).toBeVisible();
  await page.getByRole("navigation", { name: "Note categories" }).getByRole("button", { name: "Segments" }).click();
  await expect(page.getByText(/^Not summarised\./)).toBeVisible();
});

test("a footnote error can be retried", async ({ page }) => {
  await page.route(`**/api/v1/companies/${TICKER}/footnote-facts`, (route) =>
    route.fulfill({ status: 500, json: { title: "Internal Server Error", status: 500 } }),
  );
  await page.goto(tab);
  await expect(page.getByText("Footnote figures could not be loaded.")).toBeVisible({ timeout: 30_000 });
  await expect(page.getByRole("button", { name: "Try again" })).toBeVisible();
});
