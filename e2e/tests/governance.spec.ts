import { expect, test } from "@playwright/test";

import { TICKER } from "./helpers";

// Phase 7g (Instructions/32_phase7g_governance_def14a.md): the Governance tab shows the board
// snapshot under the AI marker (each answer opens its quote), the CEO pay table marked as
// extracted from filing tables, the validated pay ratio and the pay-versus-performance chart; a
// partly extracted proxy says what is missing; a company with no proxy says how many were
// ingested. The first test needs the dev stack after `make governance-backfill`; the others mock
// the response. Spec refs: FR-GV-012, FR-GV-012, FR-GV-012.

const tab = `/company/${TICKER}/governance`;

const filing = {
  filing_id: "209",
  filing_type: "DEF 14A",
  filing_date: "2026-05-12",
  period_end: "2026-06-24",
  accession_number: "0001045810-26-000036",
};

test("populated: board facts, CEO pay, pay ratio and pay versus performance", async ({ page }) => {
  await page.goto(tab);
  await expect(page.getByText(/From the proxy statement covering fiscal \d{4}, filed/)).toBeVisible();
  const board = page.getByRole("region", { name: "Board" });
  await expect(board.getByTitle("Generated by AI from cited sources")).toBeVisible();
  await expect(board.getByText("Board size")).toBeVisible();

  const pay = page.getByRole("region", { name: "CEO pay" });
  await expect(pay.getByText("Extracted from filing tables")).toBeVisible();
  await expect(page.getByTestId("pay-ratio")).toContainText(/\d+:1/);
  await expect(page.getByRole("heading", { name: "CEO pay vs shareholder return" })).toBeVisible();

  await page.getByTestId("pay-ratio").getByRole("button").click();
  await expect(page.getByRole("dialog")).toHaveAccessibleName("Source");
});

test("partially populated: pending board facts and missing sections are stated", async ({ page }) => {
  await page.route(`**/api/v1/companies/${TICKER}/governance`, (route) =>
    route.fulfill({
      json: {
        company_ticker: TICKER,
        fiscal_year: 2026,
        fiscal_year_source: "summary_compensation_table",
        filing,
        available_years: [2026],
        proxies_ingested: 1,
        reason: null,
        coverage: { summary_compensation_table: true, pay_versus_performance: false, board: true },
        facts: { status: "pending", model: null, fields: [], independence_ratio: null, reason: "Not extracted yet." },
        compensation: {
          rows: [
            {
              person: "Pat Example Chief Executive Officer",
              role: "peo",
              fiscal_year: 2026,
              components: { salary: "1000000.00000000" },
              total: "1000000.00000000",
              source_id: "209_SCT_t0065",
            },
          ],
          rejected_rows: 2,
          reason: null,
        },
        pay_vs_performance: {
          points: [],
          company_selected_measure: null,
          reason: "This proxy has no Pay Versus Performance XBRL facts.",
        },
        pay_ratio: { reason: "No validated CEO total in this proxy to check a pay ratio against." },
      },
    }),
  );
  await page.goto(tab);
  await expect(page.getByText(/Not read yet/)).toBeVisible();
  await expect(page.getByText("Not found in this proxy: Pay Versus Performance.")).toBeVisible();
  await expect(page.getByText("This proxy has no Pay Versus Performance XBRL facts.")).toBeVisible();
  await expect(page.getByText(/2 rows of the table did not add up/)).toBeVisible();
  await expect(page.getByTestId("pay-ratio")).toContainText("No validated CEO total");
});

test("empty: no proxy ingested says so", async ({ page }) => {
  await page.route(`**/api/v1/companies/${TICKER}/governance`, (route) =>
    route.fulfill({
      json: {
        company_ticker: TICKER,
        fiscal_year: null,
        fiscal_year_source: null,
        filing: null,
        available_years: [],
        proxies_ingested: 0,
        reason: "No DEF 14A proxy statement has been processed for this company yet.",
        coverage: {},
      },
    }),
  );
  await page.goto(tab);
  await expect(page.getByText(/Proxy statements ingested for \w+: 0\./)).toBeVisible();
});
